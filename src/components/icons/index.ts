/**
 * Dukavo's icon set — Lucide, re-exported here and imported nowhere else.
 *
 * Two rules this module enforces for the whole application:
 *
 *   1. One system. No component ever imports an icon package directly, so the
 *      stroke weight, optical size and rendering stay identical everywhere and
 *      swapping the library later is a single-file change.
 *   2. Consistent gesture. Icons inherit `currentColor` and are sized by the
 *      component (`size` prop), never by a CSS rule on the SVG, so an icon
 *      always matches the text it sits beside in both scripts.
 *
 * Icons are decorative by default (`aria-hidden`). Anything that conveys
 * meaning on its own sets `aria-label` at the call site.
 */

